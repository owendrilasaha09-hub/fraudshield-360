-- 7. ANALYTICS VIEWS
-- ============================================================================
CREATE OR REPLACE VIEW ANALYTICS.V_VERIFICATION_METRICS AS
WITH base AS (
    SELECT cve.RESPONSE_TYPE, cve.RESPONSE_TIME_MINUTES
    FROM AGENTS.CUSTOMER_VERIFICATION_EVENTS cve
    INNER JOIN AGENTS.FRAUD_ALERTS fa ON cve.CASE_ID = fa.CASE_ID
    WHERE cve.RESPONSE_TYPE IS NOT NULL
)
SELECT COUNT(*) AS total_verifications_sent,
    COUNT(CASE WHEN RESPONSE_TYPE='USER_CONFIRMED' THEN 1 END) AS confirmed_count,
    COUNT(CASE WHEN RESPONSE_TYPE='USER_REQUESTED_REVIEW' THEN 1 END) AS review_count,
    COUNT(CASE WHEN RESPONSE_TYPE='USER_REJECTED' THEN 1 END) AS rejected_count,
    COUNT(CASE WHEN RESPONSE_TYPE='VERIFICATION_TIMEOUT' THEN 1 END) AS timeout_count,
    ROUND(confirmed_count*100.0/NULLIF(total_verifications_sent,0),2) AS acceptance_rate_pct,
    ROUND(review_count*100.0/NULLIF(total_verifications_sent,0),2) AS hold_rate_pct,
    ROUND(rejected_count*100.0/NULLIF(total_verifications_sent,0),2) AS rejection_rate_pct,
    ROUND(timeout_count*100.0/NULLIF(total_verifications_sent,0),2) AS timeout_rate_pct,
    ROUND(AVG(CASE WHEN RESPONSE_TYPE!='VERIFICATION_TIMEOUT' THEN RESPONSE_TIME_MINUTES END),2) AS avg_response_time_minutes_excl_timeouts
FROM base;

CREATE OR REPLACE VIEW ANALYTICS.V_FRAUD_RISK_DASHBOARD AS
SELECT DATE_TRUNC('DAY', TXN_TIMESTAMP) AS metric_date,
    COUNT(*) AS total_transactions,
    COUNT(CASE WHEN RISK_SCORE > 0 THEN 1 END) AS flagged_transactions,
    ROUND(flagged_transactions*100.0/NULLIF(total_transactions,0),2) AS flag_rate_pct,
    AVG(RISK_SCORE) AS avg_risk_score,
    SUM(CASE WHEN RISK_TIER IN ('HIGH','CRITICAL') THEN AMOUNT ELSE 0 END) AS high_risk_volume
FROM CURATED.TRANSACTION_ENRICHED GROUP BY metric_date;

CREATE OR REPLACE VIEW ANALYTICS.V_AML_EXPOSURE_SUMMARY AS
SELECT t.GEO_COUNTRY AS transaction_country, a.DOMICILE_COUNTRY AS account_country,
    a.RISK_TIER AS account_risk_tier, COUNT(*) AS transaction_count,
    SUM(t.AMOUNT) AS total_exposure_amount,
    SUM(CASE WHEN t.RISK_TIER IN ('HIGH','CRITICAL') THEN t.AMOUNT ELSE 0 END) AS high_risk_exposure,
    COUNT(CASE WHEN t.SIGNAL_WATCHLIST_MATCH THEN 1 END) AS watchlist_hits,
    COUNT(DISTINCT t.ACCOUNT_ID) AS unique_accounts_exposed,
    ROUND(high_risk_exposure*100.0/NULLIF(total_exposure_amount,0),2) AS high_risk_pct_of_volume
FROM CURATED.TRANSACTION_ENRICHED t
LEFT JOIN RAW.RAW_ACCOUNTS a ON t.ACCOUNT_ID = a.ACCOUNT_ID
GROUP BY t.GEO_COUNTRY, a.DOMICILE_COUNTRY, a.RISK_TIER;

CREATE OR REPLACE VIEW ANALYTICS.V_KYC_COMPLIANCE_STATUS AS
SELECT KYC_STATUS, RISK_TIER, ACCOUNT_TYPE, DOMICILE_COUNTRY,
    COUNT(*) AS account_count,
    ROUND(COUNT(*)*100.0/SUM(COUNT(*)) OVER(),2) AS pct_of_total,
    ROUND(COUNT(CASE WHEN KYC_STATUS='VERIFIED' THEN 1 END) OVER()*100.0/NULLIF(COUNT(*) OVER(),0),2) AS overall_compliance_rate_pct
FROM RAW.RAW_ACCOUNTS GROUP BY KYC_STATUS, RISK_TIER, ACCOUNT_TYPE, DOMICILE_COUNTRY;

CREATE OR REPLACE VIEW ANALYTICS.V_CASE_RESOLUTION_METRICS AS
SELECT CASE_STATUS, RISK_TIER, ALERT_TYPE, ASSIGNED_ANALYST,
    COUNT(DISTINCT fa.CASE_ID) AS total_cases,
    AVG(cve.RESPONSE_TIME_MINUTES) AS avg_response_time_minutes
FROM AGENTS.FRAUD_ALERTS fa
LEFT JOIN AGENTS.CUSTOMER_VERIFICATION_EVENTS cve ON fa.CASE_ID = cve.CASE_ID
GROUP BY CASE_STATUS, RISK_TIER, ALERT_TYPE, ASSIGNED_ANALYST;

