-- 6. CURATED SCHEMA — Dynamic Table
-- ============================================================================
CREATE OR REPLACE DYNAMIC TABLE CURATED.TRANSACTION_ENRICHED
  TARGET_LAG = '5 minutes'
  WAREHOUSE = COMPUTE_WH
AS
WITH base AS (
    SELECT t.*,
        CASE WHEN COUNT(*) OVER (PARTITION BY t.ACCOUNT_ID ORDER BY t.TXN_TIMESTAMP
            RANGE BETWEEN INTERVAL '1 HOUR' PRECEDING AND CURRENT ROW) > 3
            THEN TRUE ELSE FALSE END AS signal_velocity,
        CASE WHEN t.AMOUNT > 5 * MEDIAN(t.AMOUNT) OVER (PARTITION BY t.ACCOUNT_ID)
            THEN TRUE ELSE FALSE END AS signal_amount_anomaly,
        CASE WHEN t.GEO_COUNTRY != COALESCE(a.DOMICILE_COUNTRY, t.GEO_COUNTRY)
            THEN TRUE ELSE FALSE END AS signal_geo_mismatch,
        CASE WHEN w.ENTITY_NAME IS NOT NULL THEN TRUE ELSE FALSE END AS signal_watchlist_match,
        CASE WHEN MOD(t.AMOUNT, 1000) = 0 AND t.AMOUNT >= 1000 THEN TRUE ELSE FALSE END AS signal_round_number,
        CASE WHEN t.AMOUNT BETWEEN 9000 AND 9999 THEN TRUE ELSE FALSE END AS signal_structuring
    FROM RAW.RAW_TRANSACTIONS t
    LEFT JOIN RAW.RAW_ACCOUNTS a ON t.ACCOUNT_ID = a.ACCOUNT_ID
    LEFT JOIN (SELECT DISTINCT ENTITY_NAME FROM RAW.RAW_WATCHLIST) w
        ON CONTAINS(UPPER(t.MERCHANT), UPPER(SPLIT_PART(w.ENTITY_NAME, ' ', 1)))
        AND LENGTH(SPLIT_PART(w.ENTITY_NAME, ' ', 1)) > 3
),
scored AS (
    SELECT *, LEAST(100,
        (signal_velocity::INT*15) + (signal_amount_anomaly::INT*25) + (signal_geo_mismatch::INT*20) +
        (signal_watchlist_match::INT*30) + (signal_round_number::INT*5) + (signal_structuring::INT*20)
    ) AS risk_score FROM base
)
SELECT TXN_ID, ACCOUNT_ID, AMOUNT, MERCHANT, GEO_COUNTRY, GEO_CITY, CHANNEL, TXN_TIMESTAMP, DEVICE_ID,
    signal_velocity, signal_amount_anomaly, signal_geo_mismatch, signal_watchlist_match,
    signal_round_number, signal_structuring, risk_score,
    CASE WHEN risk_score >= 75 THEN 'CRITICAL' WHEN risk_score >= 50 THEN 'HIGH'
         WHEN risk_score >= 25 THEN 'MEDIUM' ELSE 'LOW' END AS risk_tier,
    CONCAT('Signals: ', IFF(signal_velocity,'VELOCITY ',''), IFF(signal_amount_anomaly,'AMOUNT_ANOMALY ',''),
        IFF(signal_geo_mismatch,'GEO_MISMATCH ',''), IFF(signal_watchlist_match,'WATCHLIST ',''),
        IFF(signal_round_number,'ROUND_NUM ',''), IFF(signal_structuring,'STRUCTURING ',''),
        '| Score: ', risk_score::VARCHAR) AS signal_explanation_admin,
    CASE WHEN risk_score >= 75 THEN 'This transaction was flagged due to multiple unusual indicators.'
         WHEN risk_score >= 50 THEN 'We noticed some unusual activity on this transaction.'
         WHEN risk_score >= 25 THEN 'Minor flag due to slight deviation from usual patterns.'
         ELSE 'Transaction appears consistent with normal activity.' END AS signal_explanation_customer
FROM scored;

